describe("exportQuizSessionReviewDocument", () => {
  it("creates a downloadable pdf blob", async () => {
    const originalCreateObjectURL = URL.createObjectURL;
    const originalRevokeObjectURL = URL.revokeObjectURL;
    const createObjectUrlSpy = jest.fn().mockReturnValue("blob:quiz-export");
    const revokeObjectUrlSpy = jest.fn();
    Object.defineProperty(URL, "createObjectURL", {
      configurable: true,
      writable: true,
      value: createObjectUrlSpy,
    });
    Object.defineProperty(URL, "revokeObjectURL", {
      configurable: true,
      writable: true,
      value: revokeObjectUrlSpy,
    });
    const appendChildSpy = jest.spyOn(document.body, "appendChild");
    const clickSpy = jest.spyOn(HTMLAnchorElement.prototype, "click").mockImplementation(() => {});
    jest.useFakeTimers();

    const result = await exportQuizSessionReviewDocument({
      noteTitle: "Photosynthesis Notes",
      noteSubject: "Biology",
      quizTypeLabel: "Quick Review",
      review: BASE_REVIEW,
      exportedAt: new Date("2026-04-14T08:00:00Z"),
    });

    expect(result.filename).toBe("notelib-quiz-photosynthesis-notes-2026-04-14.pdf");
    expect(createObjectUrlSpy).toHaveBeenCalled();
    expect(appendChildSpy).toHaveBeenCalled();
    expect(clickSpy).toHaveBeenCalled();

    jest.runOnlyPendingTimers();
    expect(revokeObjectUrlSpy).toHaveBeenCalledWith("blob:quiz-export");

    clickSpy.mockRestore();
    appendChildSpy.mockRestore();
    Object.defineProperty(URL, "createObjectURL", {
      configurable: true,
      writable: true,
      value: originalCreateObjectURL,
    });
    Object.defineProperty(URL, "revokeObjectURL", {
      configurable: true,
      writable: true,
      value: originalRevokeObjectURL,
    });
    jest.useRealTimers();
  });
});
