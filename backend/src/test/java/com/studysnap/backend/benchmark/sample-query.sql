-- v0.174.0 LLM benchmark: input sample. READ-ONLY (a single SELECT). Owner-run with psql.
-- Emits one JSONL line per benchmark generation, in the shape README.md specifies.
--
--   mkdir -p backend/target/llm-benchmark
--   psql "<External Database URL>" -At -f backend/src/test/java/com/studysnap/backend/benchmark/sample-query.sql \
--        > backend/target/llm-benchmark/full.jsonl
--   head -1 backend/target/llm-benchmark/full.jsonl > backend/target/llm-benchmark/smoke.jsonl
--
-- The output holds note text: keep it under backend/target/ (git-ignored) and never commit it.
-- Expected output: 81 lines = 40 A + 32 B (8 per method) + 5 C + 4 D.
--
-- Sample rules:
--   - PUBLIC, ORIGINAL notes (not copies) that have a Study Pack, with 400–12,000 characters of text.
--   - The text is normalised the way StudyPackService.normalizeAndValidateText does
--     (trim, then collapse every whitespace run to one space).
--   - Stratified by Domain Context (falling back to subject): one note per stratum first, then
--     round-robin, all in a deterministic order (md5 with a fixed salt), so a re-run returns the same
--     sample.
--   - Context fields:
--     - learnerLevel = the owner's profile level;
--     - noteLearnerLevel = the note's level;
--     - domainContext = the note's own value;
--     - courseProgram = the single joined catalog program if exactly one exists, else the note's
--       course_program.
--     This approximates StudyPackGenerationContextResolver and applies the SAME context to every model,
--     so the comparison stays fair.
--   - Leg B reuses each note's existing Study Pack (generated by gpt-4.1-mini) as identical input for
--     all three models. Say so in the results.
--   - Leg D = the PUBLIC source notes of the 6 packs repaired on 2026-10-16: 4 distinct texts. The 2
--     private copies are excluded; their text is identical to their public source.
WITH base AS (
  SELECT n.id, n.title, n.subject, n.tags, n.domain_context, n.learner_level AS note_level,
         u.learner_level AS owner_level, n.course_program,
         regexp_replace(btrim(n.content), '\s+', ' ', 'g') AS note_text,
         sp.title AS sp_title, sp.summary AS sp_summary, sp.key_concepts, sp.quiz,
         (SELECT CASE WHEN count(*) = 1 THEN min(cp.name) END
            FROM note_course_program ncp JOIN course_programs cp ON cp.id = ncp.course_program_id
           WHERE ncp.note_id = n.id) AS joined_program,
         coalesce(n.domain_context, n.subject, 'none') AS stratum,
         md5(n.id::text || 'v0174') AS ord
  FROM notes n
  JOIN users u ON u.id = n.owner_user_id AND u.deleted_at IS NULL
  JOIN study_packs sp ON sp.note_id = n.id
  WHERE n.visibility = 'PUBLIC' AND n.copied_from_note_id IS NULL
    AND length(regexp_replace(btrim(n.content), '\s+', ' ', 'g')) BETWEEN 400 AND 12000
    AND jsonb_typeof(sp.key_concepts) = 'array' AND jsonb_array_length(sp.key_concepts) >= 2
),
ranked AS (
  SELECT b.*, row_number() OVER (ORDER BY rn_in_stratum, ord) AS pick
  FROM (SELECT base.*, row_number() OVER (PARTITION BY stratum ORDER BY ord) AS rn_in_stratum FROM base) b
),
ctx AS (
  SELECT r.*, jsonb_build_object(
           'tags', coalesce(to_jsonb(r.tags), '[]'::jsonb),
           'learnerLevel', r.owner_level,
           'noteLearnerLevel', r.note_level,
           'domainContext', r.domain_context,
           'subject', r.subject,
           'courseProgram', coalesce(r.joined_program, r.course_program)) AS c,
         coalesce((SELECT jsonb_agg(q->>'question') FROM jsonb_array_elements(r.quiz) q), '[]'::jsonb) AS disallowed
  FROM ranked r
),
leg_a AS (
  SELECT 1 AS grp, pick AS o, c || jsonb_build_object('id', 'A-' || left(id::text, 8), 'leg', 'A', 'noteText', note_text) AS line
  FROM ctx WHERE pick BETWEEN 1 AND 40
),
leg_b AS (
  SELECT 2 AS grp, pick AS o, c || jsonb_build_object(
           'id', 'B-' || left(id::text, 8), 'leg', 'B',
           'method', (ARRAY['generateChallengeQuiz','generateBoardExamQuiz','generateAdaptivePracticeQuiz','generateLongExam'])[((pick - 41) % 4) + 1],
           'studyPackTitle', sp_title, 'studyPackSummary', sp_summary, 'sourceNoteText', note_text,
           'keyConcepts', key_concepts, 'disallowedQuestions', disallowed,
           'weakConcepts', jsonb_build_array(key_concepts->0, key_concepts->1),
           'difficulty', 'mixed') AS line
  FROM ctx WHERE pick BETWEEN 41 AND 72
),
leg_c AS (
  SELECT 3 AS grp, pick AS o, c || jsonb_build_object('id', 'C-' || left(id::text, 8), 'leg', 'C', 'topic', title) AS line
  FROM ctx WHERE pick BETWEEN 73 AND 77
),
leg_d AS (
  SELECT 4 AS grp, 0 AS o, line FROM (
    SELECT DISTINCT ON (md5(b.note_text))
           jsonb_build_object(
             'tags', coalesce(to_jsonb(b.tags), '[]'::jsonb), 'learnerLevel', b.owner_level,
             'noteLearnerLevel', b.note_level, 'domainContext', b.domain_context, 'subject', b.subject,
             'courseProgram', coalesce(b.joined_program, b.course_program),
             'id', 'D-' || left(b.id::text, 8), 'leg', 'D', 'regression', true, 'noteText', b.note_text) AS line
    FROM (
      SELECT n.id, n.tags, n.domain_context, n.learner_level AS note_level, u.learner_level AS owner_level,
             n.subject, n.course_program,
             regexp_replace(btrim(n.content), '\s+', ' ', 'g') AS note_text,
             (SELECT CASE WHEN count(*) = 1 THEN min(cp.name) END FROM note_course_program ncp
                JOIN course_programs cp ON cp.id = ncp.course_program_id WHERE ncp.note_id = n.id) AS joined_program
      FROM study_packs sp JOIN notes n ON n.id = sp.note_id JOIN users u ON u.id = n.owner_user_id
      WHERE sp.id IN ('b64de9fd-982b-42a7-b59c-110861b82966','3e671707-8984-4e51-8386-04cacd5d3667',
                      '95aab696-5a9d-47c0-99f6-a9cca1736295','5fe4e2be-e8d0-4a29-81b6-e1bc34077fbc',
                      'd83013bd-3bd0-408e-b64e-8b7cbcf26285','deaa49eb-f001-4ae1-bb9a-b5ac038eec93')
        AND n.visibility = 'PUBLIC'
        AND length(regexp_replace(btrim(n.content), '\s+', ' ', 'g')) BETWEEN 1 AND 12000
    ) b ORDER BY md5(b.note_text), b.id
  ) d
)
SELECT line::text FROM (
  SELECT * FROM leg_a UNION ALL SELECT * FROM leg_b UNION ALL SELECT * FROM leg_c UNION ALL SELECT * FROM leg_d
) all_legs ORDER BY grp, o;
